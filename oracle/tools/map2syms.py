"""Turn a TLINK .MAP (linked with /s) into machine-readable symbol tables.

  map2syms.py sym    RCK4.MAP oracle/docs/symbols/k4.sym     # TSV symbol table
  map2syms.py ghidra oracle/docs/symbols/k4.sym             # (see oracle/docs/symbols/ghidra_import_syms.py)
  map2syms.py bp     oracle/docs/symbols/k4.sym RF_Refresh --load-seg 0x1A2B   # DOSBox-X debugger command
  map2syms.py lookup oracle/docs/symbols/k4.sym 1654:1C6E   # reverse lookup (also 0xLINEAR)
  map2syms.py states oracle/docs/symbols/k4.sym oracle/dos/KEEN4-6 oracle/dos/KEEN4-6/KEEN4  # statetype coverage

.sym columns (tab separated, '#' lines are comments):
  name   symbol with the C leading underscore stripped (assembler/RTL symbols keep their form)
  seg    link-time frame number in hex, RELATIVE to the load segment (image start / 16)
  off    offset within that frame, hex
  linear seg*16+off in hex: byte offset into the *unpacked* EXE image (after the header)
  kind   code | data
  segment  the TLINK segment the address falls in (_TEXT, ID_RF_TEXT, _DATA, _BSS, ...)
At run time the real address is (load_segment + seg):off; load_segment = PSP segment + 0x10.
Only PUBLIC symbols exist in a TLINK map (static functions/variables are absent).
"""
import re, sys, argparse, os

SEGRE = re.compile(r'^\s*([0-9A-F]{5})H\s+([0-9A-F]{5})H\s+([0-9A-F]{5})H\s+(\S+)\s+(\S+)\s*$')
PUBRE = re.compile(r'^\s*([0-9A-F]{4}):([0-9A-F]{4})(\s+idle)?\s+(\S+)\s*$')


def parse_map(path):
    segs, pubs, mode = [], [], None
    for line in open(path, encoding='latin-1'):
        line = line.rstrip('\r\n')
        if 'Detailed map of segments' in line: mode = 'detail'
        elif 'Publics by Name' in line: mode = 'byname'
        elif 'Publics by Value' in line: mode = 'byvalue'
        elif mode is None:
            m = SEGRE.match(line)
            if m:
                s, e, ln, name, cls = m.groups()
                segs.append((int(s, 16), int(e, 16), int(ln, 16), name, cls))
        elif mode == 'byvalue':
            m = PUBRE.match(line)
            if m:
                pubs.append((int(m.group(1), 16), int(m.group(2), 16), m.group(4)))
    return segs, pubs


def classify(segs, lin):
    best = None
    for s, e, ln, name, cls in segs:
        if ln and s <= lin <= e: best = (name, cls)
    if best is None:  # zero-length segment at end, or between segments
        for s, e, ln, name, cls in segs:
            if s <= lin: best = (name, cls)
    return best


def cname(n):
    return n[1:] if n.startswith('_') and not n.startswith('__') else n


def cmd_sym(a):
    segs, pubs = parse_map(a.map)
    rows = []
    for seg, off, name in pubs:
        lin = seg * 16 + off
        sn, cls = classify(segs, lin)
        rows.append((lin, cname(name), seg, off, 'code' if cls == 'CODE' else 'data', sn))
    rows.sort(key=lambda r: (r[0], r[1]))
    with open(a.out, 'w') as f:
        f.write(f'# SPDX-License-Identifier: GPL-2.0-or-later\n# generated by tools/map2syms.py from {os.path.basename(a.map)}; seg is relative to the load segment\n')
        f.write('#name\tseg\toff\tlinear\tkind\tsegment\n')
        for lin, n, seg, off, kind, sn in rows:
            f.write(f'{n}\t{seg:04X}\t{off:04X}\t{lin:05X}\t{kind}\t{sn}\n')
    k = sum(1 for r in rows if r[4] == 'code')
    print(f'{a.out}: {len(rows)} symbols ({k} code, {len(rows)-k} data)')


def load_sym(path):
    out = []
    for line in open(path):
        if line.startswith('#') or not line.strip(): continue
        n, seg, off, lin, kind, sn = line.rstrip('\n').split('\t')
        out.append((n, int(seg, 16), int(off, 16), int(lin, 16), kind, sn))
    return out


def cmd_bp(a):
    syms = {s[0]: s for s in load_sym(a.sym)}
    ls = int(a.load_seg, 16) if a.load_seg else 0
    for n in a.names:
        s = syms.get(n) or syms.get('_' + n)
        if not s: sys.exit(f'no such symbol: {n}')
        print(f'BP {(ls + s[1]) & 0xFFFF:04X}:{s[2]:04X}' + ('' if a.load_seg else '   ; seg is load-segment-relative: add the load segment') + f'   ; {s[0]} ({s[4]})')


def cmd_lookup(a):
    syms = load_sym(a.sym)
    if ':' in a.addr:
        sg, of = a.addr.split(':'); lin = int(sg, 16) * 16 + int(of, 16)
    else:
        lin = int(a.addr, 16)
    if a.load_seg: lin -= int(a.load_seg, 16) * 16
    cand = [s for s in syms if s[3] <= lin and (s[4] == 'code') == (classify_kind(syms, lin) == 'code')]
    if not cand: sys.exit('no symbol')
    s = max(cand, key=lambda s: s[3])
    print(f'{s[0]}+0x{lin - s[3]:X}\t{s[4]}\t{s[5]}')


def classify_kind(syms, lin):
    prev = [s for s in syms if s[3] <= lin]
    return max(prev, key=lambda s: s[3])[4] if prev else 'code'


def cmd_ghidra(a):
    print('Use: analyzeHeadless ... -postScript ghidra_import_syms.py <k4.sym> <loadseg-hex> (see oracle/docs/SYMBOLS.md)')


STATERE = re.compile(r'^\s*(static\s+)?(?:far\s+)?statetype\s+(\w+)\s*(?:\[\w*\])?\s*=', re.M)


def cmd_states(a):
    names = {s[0] for s in load_sym(a.sym)}
    found = {}
    for d in a.dirs:
        for fn in sorted(os.listdir(d)):
            if fn.upper().endswith(('.C', '.H')):
                for m in STATERE.finditer(open(os.path.join(d, fn), encoding='latin-1').read()):
                    found[m.group(2)] = (bool(m.group(1)), fn)
    inmap = sorted(n for n in found if n in names)
    static = sorted(n for n in found if n not in names and found[n][0])
    absent = sorted(n for n in found if n not in names and not found[n][0])
    print(f'statetype definitions in source: {len(found)}; in map: {len(inmap)}; static: {len(static)}; non-static but not in map: {len(absent)}')
    for n in static: print('  static   ', n, found[n][1])
    for n in absent: print('  not-in-map', n, found[n][1])


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = p.add_subparsers(dest='c', required=True)
    s = sp.add_parser('sym'); s.add_argument('map'); s.add_argument('out'); s.set_defaults(f=cmd_sym)
    s = sp.add_parser('bp'); s.add_argument('sym'); s.add_argument('names', nargs='+'); s.add_argument('--load-seg'); s.set_defaults(f=cmd_bp)
    s = sp.add_parser('lookup'); s.add_argument('sym'); s.add_argument('addr'); s.add_argument('--load-seg'); s.set_defaults(f=cmd_lookup)
    s = sp.add_parser('states'); s.add_argument('sym'); s.add_argument('dirs', nargs='+'); s.set_defaults(f=cmd_states)
    s = sp.add_parser('ghidra'); s.add_argument('sym'); s.set_defaults(f=cmd_ghidra)
    a = p.parse_args(); a.f(a)


if __name__ == '__main__':
    main()
